export function mount(container, { lang = getLang(), getAddress = () => "", client } = {}) {
  const root = document.createElement("section");
  root.className = "pane bo-pane";
  root.innerHTML = markup();
  container.append(root);
  const life = new AbortController();
  const q = selector => root.querySelector(selector);
  const all = selector => [...root.querySelectorAll(selector)];
  const loc = key => pickLang(TXT[key], lang);
  const tabButton = id => q(`[data-tab="${id}"]`);
  const form = id => q(`[data-form="${id}"]`);
  const cachoForm = form("cacho");
  const setup = form("raffle");
  const tickets = form("ticket");
  const sim = form("simulation");
  const value = (f, name) => f.elements.namedItem(name).value.trim();
  const horizon = client || createHorizonClient({
    fetchImpl: (url, init) => fetch(url, { ...init, signal: AbortSignal.any([life.signal, AbortSignal.timeout(8000)]) }),
  });
  let tab = "cacho";
  let scene;
  let displayed = null;
  let player = 0;
  let raffle = null;
  let saved = null;
  let storageMessage = "";
  let setupError = "";
  let creating = false;
  let raffleLife = new AbortController();
  const rounds = {};
  let latestDice = null;

  function newRound(id, signal = life.signal, hooks) {
    return createRound(horizon, signal, () => {
      renderRound(id);
      if (id === "cacho" || id === "cacho-replay") {
        const result = rounds[id].state.result;
        if (result) {
          latestDice = result;
          player = 0;
        } else if (latestDice && ![rounds.cacho, rounds["cacho-replay"]].some(r => r?.state.result === latestDice)) {
          latestDice = null;
        }
        renderScene();
      }
    }, hooks);
  }

  function renderScene(moving = true) {
    if (tab !== "cacho") {
      scene?.destroy();
      scene = null;
      displayed = null;
      return;
    }
    const rows = latestDice?.rows || [];
    const select = q("[data-player]");
    q(".bo-select-player").hidden = !rows.length;
    if (select.dataset.size !== String(rows.length) || select._rows !== rows && rows.length) {
      select.replaceChildren(...rows.map((r, i) => new Option(r.name, String(i))));
      select.dataset.size = String(rows.length);
      select._rows = rows;
    }
    select.value = String(player);
    const values = rows[player]?.dice || previewDice;
    q(".bo-faces").textContent = values.map(n => String.fromCodePoint(0x267f + n)).join(" ");
    if (!scene) scene = mountDice(q(".bo-stage"));
    if (displayed !== values) {
      scene.show(values, moving && values !== previewDice);
      displayed = values;
    }
  }

  function resultMarkup(state, isCacho) {
    if (!state.result) return "";
    const rows = state.result.rows;
    const winner = `<p class="bo-winner">${loc("winner")} · <strong>${escapeHtml(rows[0].name)}</strong></p>`;
    if (!isCacho) return winner;
    return winner + `<ol class="bo-scores">${rows.map(row => `<li><strong>${escapeHtml(row.name)}</strong>
      <span class="bo-roll">${row.dice.join(" · ")}</span>
      <span>${loc(row.hand)} · ${row.points} ${loc("points")}</span></li>`).join("")}</ol>`;
  }

  function renderRound(id) {
    const round = rounds[id];
    const s = round.state;
    const replay = id.endsWith("-replay");
    const cacho = id.startsWith("cacho");
    const retryable = s.phase === "offline" || s.phase === "pending";
    const host = q(`[data-round="${id}"]`);
    const status = s.phase === "invalid" ? (replay ? "badCode" : "invalidList") : s.phase;
    const meta = s.draw ? `<dl class="bo-meta"><dt>${loc("commit")}</dt><dd><code>${s.draw.commitment}</code></dd>
      ${s.draw.ledger ? `<dt>${loc("target")}</dt><dd>${s.draw.ledger}</dd>` : ""}</dl>` : "";
    host.innerHTML = `${meta}<p role="status" class="bo-status">${TXT[status] ? loc(status) : ""}</p>
      ${s.code && !replay ? `${s.phase === "waiting" ? `<p>${loc("lockHint")}</p>` : ""}
      <label>${loc("code")}<textarea readonly rows="2" class="bo-code">${escapeHtml(s.code)}</textarea></label>` : ""}
      ${resultMarkup(s, cacho)}
      <div class="bo-actions">${retryable ? button("retry", "retry") : ""}
      ${retryable && id === "cacho" ? button("practiceBtn", "practice") : ""}
      ${s.draw && !round.busy() && id === "cacho" ? button("newRound", "new") : ""}</div>`;
    host.querySelectorAll("[data-bo-text]").forEach(el => { el.textContent = loc(el.dataset.boText); });
    if (id === "cacho") {
      cachoForm.elements.names.readOnly = round.busy() || Boolean(s.draw);
      cachoForm.querySelector("button").hidden = cachoForm.elements.names.readOnly;
    }
    if (replay) {
      const verify = host.previousElementSibling;
      verify.querySelector("button").disabled = round.busy();
      verify.elements.code.readOnly = round.busy();
    }
    if (id === "raffle") q("[data-new-raffle]").hidden = s.phase !== "done";
  }

  function saveRaffle(next) {
    try {
      const previous = localStorage.getItem(RAFFLE_KEY);
      if (previous !== saved) {
        loadRaffle();
        return false;
      }
      const json = JSON.stringify(next);
      localStorage.setItem(RAFFLE_KEY, json);
      saved = json;
      storageMessage = "";
    } catch { storageMessage = "storage"; }
    raffle = next;
    q("[data-storage]").textContent = storageMessage ? loc(storageMessage) : "";
    return true;
  }

  function raffleRound() {
    return newRound("raffle", raffleLife.signal, {
      onTarget: ledger => saveRaffle({ ...raffle, ledger }),
      onHash: ledgerHash => saveRaffle({ ...raffle, ledgerHash }),
    });
  }

  function loadRaffle() {
    raffleLife.abort();
    raffleLife = new AbortController();
    rounds.raffle = raffleRound();
    raffle = null;
    try {
      saved = localStorage.getItem(RAFFLE_KEY);
      raffle = restoreRaffle(saved);
      storageMessage = "";
    } catch { storageMessage = "unreadable"; }
    setupError = "";
    renderRaffle();
    renderRound("raffle");
    if (raffle?.closed) resumeRaffle();
  }

  function resumeRaffle() {
    const current = raffle;
    rounds.raffle.start(async () => ({
      ...await lockList("raffle", ticketNames(current.entries), current.title),
      ledger: current.ledger,
    }), current.ledgerHash);
  }

  function renderPayment() {
    const host = q("[data-payment]");
    if (!raffle || raffle.closed) {
      host.replaceChildren();
      return;
    }
    const n = ticketNumber(value(tickets, "number"));
    const full = raffle.entries.length >= MAX_TICKETS;
    const available = n && !raffle.entries.some(e => e.number === n);
    tickets.querySelector("button").disabled = !available || full;
    if (!available || full) {
      host.textContent = loc(full ? "ticketLimit" : "ticketError");
      return;
    }
    const uri = ticketUri(raffle, n);
    host.innerHTML = `<div class="bo-qr">${qrSvg(uri)}</div><strong>RIFA-${n}</strong>
      <p>${loc("payHint")}</p><a href="${escapeHtml(uri)}">${loc("wallet")}</a>`;
    host.querySelector("svg").setAttribute("aria-label", `QR · RIFA-${n}`);
  }

  function renderRaffle() {
    setup.hidden = Boolean(raffle);
    setup.querySelector("button").disabled = creating;
    q("[data-raffle-error]").textContent = setupError ? loc(setupError) : "";
    q("[data-storage]").textContent = storageMessage ? loc(storageMessage) : "";
    q("[data-raffle-detail]").hidden = !raffle;
    if (!raffle) {
      if (!setup.elements.address.value) setup.elements.address.value = getAddress() || "";
      return;
    }
    q("[data-raffle-title]").textContent = raffle.title;
    q("[data-raffle-meta]").textContent = `${loc("prize")} · ${raffle.prize}　${loc("price")} · ${raffle.price} ${raffle.asset}`;
    q("[data-raffle-address]").textContent = raffle.address;
    q(".bo-tickets").hidden = raffle.closed;
    const close = q('[data-act="close"]');
    close.hidden = raffle.closed;
    close.disabled = !raffle.entries.length;
    q("[data-entries]").replaceChildren(...ticketNames(raffle.entries).map(name => {
      const li = document.createElement("li");
      li.textContent = name;
      return li;
    }));
    renderPayment();
  }

  function renderSimulation() {
    const host = q("[data-totals]");
    try {
      const input = Object.fromEntries([...sim.querySelectorAll("input")].map(el => [el.name, el.valueAsNumber]));
      const totals = simulateAnticretico(input);
      const fmt = new Intl.NumberFormat(({ en: "en-US", pt: "pt-BR" })[lang] || "es-BO", { maximumFractionDigits: 2 });
      host.innerHTML = `<dl>${[["saved", totals.savedRent], ["fixedBOB", totals.initialBOB], ["finalBOB", totals.finalBOB], ["delta", totals.changeBOB]]
        .map(([label, n]) => `<dt>${loc(label)}</dt><dd>${fmt.format(n)} Bs</dd>`).join("")}</dl>`;
    } catch { host.textContent = loc("validSim"); }
  }

  function selectTab(id) {
    tab = id;
    for (const key of tabs) {
      const active = key === tab;
      q("#bo-" + key).hidden = !active;
      tabButton(key).setAttribute("aria-selected", String(active));
      tabButton(key).tabIndex = active ? 0 : -1;
    }
    if (id === "raffle") renderRaffle();
    renderScene(false);
  }

  function translate() {
    all("[data-bo-text]").forEach(el => { el.textContent = loc(el.dataset.boText); });
    for (const id of Object.keys(rounds)) renderRound(id);
    renderRaffle();
    renderSimulation();
    // La ayuda por ruta la añade el panel después de montar la vista.
    const help = container.querySelector(".howto");
    if (help) {
      help.querySelector("span").textContent = pickLang(L("¿Cómo se hace?", "How do I do it?", "Como fazer?"), lang);
      help.querySelector('[data-topic="bolivia"]').textContent = "▶ " + loc("title");
    }
  }

  rounds.cacho = newRound("cacho");
  rounds["cacho-replay"] = newRound("cacho-replay");
  rounds["raffle-replay"] = newRound("raffle-replay");
  loadRaffle();
  translate();
  selectTab("cacho");

  root.addEventListener("click", event => {
    const btn = event.target.closest("button");
    if (!btn || btn.disabled) return;
    if (btn.dataset.tab) { selectTab(btn.dataset.tab); return; }
    const id = btn.closest("[data-round]")?.dataset.round;
    switch (btn.dataset.act) {
      case "retry": rounds[id].retry(); break;
      case "practice": rounds.cacho.practice(); break;
      case "new": rounds.cacho.reset(); cachoForm.elements.names.focus(); break;
      case "close":
        if (raffle && !raffle.closed && raffle.entries.length && saveRaffle({ ...raffle, closed: true })) {
          renderRaffle();
          resumeRaffle();
        }
        break;
      case "other":
        // El resultado anterior permanece guardado hasta que se cree la siguiente rifa.
        raffle = null;
        rounds.raffle.reset();
        tickets.reset(); setup.reset();
        renderRaffle();
        setup.elements.title.focus();
        break;
    }
  });
  root.addEventListener("keydown", event => {
    const index = tabs.indexOf(event.target.dataset.tab);
    if (index < 0) return;
    const next = { ArrowRight: (index + 1) % 3, ArrowLeft: (index + 2) % 3, Home: 0, End: 2 }[event.key];
    if (next == null) return;
    event.preventDefault();
    selectTab(tabs[next]); tabButton(tabs[next]).focus();
  });
  q("[data-player]").addEventListener("change", e => { player = Number(e.target.value); renderScene(); });
  cachoForm.onsubmit = e => {
    e.preventDefault();
    if (!rounds.cacho.state.draw) rounds.cacho.start(() => lockList("cacho", value(cachoForm, "names")));
  };
  for (const f of all("[data-verify]")) f.onsubmit = e => {
    e.preventDefault();
    const kind = f.dataset.verify;
    const code = value(f, "code");
    rounds[kind + "-replay"].start(() => readDrawCode(kind, code));
  };
  setup.onsubmit = async e => {
    e.preventDefault();
    if (raffle || creating) return;
    creating = true;
    setupError = "";
    const input = Object.fromEntries(["title", "prize", "price", "asset", "address"].map(key => [key, value(setup, key)]));
    renderRaffle();
    try {
      const { StrKey } = await import("@stellar/stellar-sdk");
      if (life.signal.aborted || raffle) return;
      if (!input.title || !input.prize || !validPrice(input.price) || !StrKey.isValidEd25519PublicKey(input.address)) throw new Error();
      if (saveRaffle({ ...input, entries: [], closed: false, ledger: null, ledgerHash: null })) tickets.reset();
    } catch { setupError = "invalidRaffle"; }
    finally { creating = false; if (!life.signal.aborted) renderRaffle(); }
  };
  tickets.elements.number.addEventListener("input", renderPayment);
  tickets.onsubmit = e => {
    e.preventDefault();
    if (!raffle || raffle.closed || raffle.entries.length >= MAX_TICKETS) return;
    const number = ticketNumber(value(tickets, "number"));
    const name = value(tickets, "name");
    if (!number || !name || raffle.entries.some(entry => entry.number === number)) return;
    if (!saveRaffle({ ...raffle, entries: [...raffle.entries, { number, name }] })) return;
    tickets.elements.namedItem("name").value = "";
    let next = 1;
    const used = new Set(raffle.entries.map(entry => entry.number));
    while (used.has(next)) next++;
    tickets.elements.number.value = String(next);
    renderRaffle();
  };
  sim.oninput = renderSimulation;
  sim.onsubmit = e => e.preventDefault();
  const changeLanguage = e => { lang = e.detail?.lang || getLang(); translate(); };
  const syncStorage = e => { if (e.key === RAFFLE_KEY || e.key === null) loadRaffle(); };
  window.addEventListener("awayu:lang", changeLanguage);
  window.addEventListener("storage", syncStorage);
  return {
    destroy() {
      life.abort();
      raffleLife.abort();
      scene?.destroy();
      window.removeEventListener("awayu:lang", changeLanguage);
      window.removeEventListener("storage", syncStorage);
    },
  };
}
